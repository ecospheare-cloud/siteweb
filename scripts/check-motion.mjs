import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=(await readFile(new URL('../public/app.js',import.meta.url),'utf8')).split('// Load decorative video')[1];
const listeners={},mediaListeners={},attrs={};let observer;
const classes=new Set();
const control={hidden:true,setAttribute(k,v){attrs[k]=v},addEventListener(k,f){listeners[k]=f}};
const media={matches:true,addEventListener(k,f){mediaListeners[k]=f}};
const film={dataset:{src:'/assets/ecospheare-motion.mp4'},paused:true,src:'',parentElement:{classList:{add:v=>classes.add(v),remove:v=>classes.delete(v)}},pause(){this.paused=true},load(){},getAttribute(){return this.src},removeAttribute(){this.src=''},play(){this.paused=false;return Promise.resolve()},addEventListener(){},closest(){return {}}};
const doc={hidden:false,querySelector:s=>s==='#hero-film'?film:control,addEventListener(k,f){listeners[k]=f}};
vm.runInNewContext('// Load decorative video'+source,{document:doc,matchMedia:()=>media,IntersectionObserver:class{constructor(f){observer=f}observe(){}}});
assert.equal(film.src,'');assert.equal(control.hidden,true);
media.matches=false;mediaListeners.change();assert.equal(film.paused,false);
listeners.click();assert.equal(film.paused,true);assert.equal(attrs['aria-label'],'Relancer l’animation');
listeners.click();assert.equal(film.paused,false);
observer([{isIntersecting:false}]);assert.equal(film.paused,true);
observer([{isIntersecting:true}]);assert.equal(film.paused,false);
doc.hidden=true;listeners.visibilitychange();assert.equal(film.paused,true);
media.matches=true;mediaListeners.change();assert.equal(film.src,'');assert.equal(control.hidden,true);
console.log('Motion: réduction initiale, changement de préférence, pause/reprise, hors-écran et onglet masqué vérifiés.');
